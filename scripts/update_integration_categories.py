"""Update the integration categories from Home Assistant core."""

from __future__ import annotations

from pathlib import Path

import requests

CATEGORIES_URL = (
    "https://raw.githubusercontent.com/home-assistant/core/refs/heads/dev"
    "/homeassistant/generated/integration_categories.json"
)
OUTPUT_PATH = Path(__file__).parents[1] / "custom_components/hacs/utils/integration_categories.py"

HEADER = '''"""Integration categories from Home Assistant core.

Generated by scripts/update_integration_categories.py, do not edit.
"""

INTEGRATION_CATEGORIES = {
'''


def get_integration_categories() -> set[str]:
    """Return the category slugs, subcategories as `category.subcategory`."""
    response = requests.get(CATEGORIES_URL, timeout=30)
    response.raise_for_status()
    categories = set()
    for category in response.json():
        categories.add(category["slug"])
        for subcategory in category["subcategories"]:
            categories.add(f"{category['slug']}.{subcategory['slug']}")
    return categories


def update_integration_categories(output_path: Path = OUTPUT_PATH) -> None:
    """Write the integration categories module."""
    categories = "".join(
        f'    "{category}",\n' for category in sorted(get_integration_categories())
    )
    with open(output_path, mode="w", encoding="utf-8") as file:
        file.write(f"{HEADER}{categories}}}\n")


if __name__ == "__main__":
    update_integration_categories()
